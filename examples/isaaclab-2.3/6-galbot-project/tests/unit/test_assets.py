import json

import pytest

from galbot_academy.assets import conversion, manifest


def test_conversion_params_record_post_processing():
    p = conversion.conversion_params("fixed_base", floating_base=False)
    assert p["fix_base"] is True
    assert p["post_processing"]["mimic_natural_frequency"] == 1000.0  # 6.1.2：默认 25 太软
    assert p["post_processing"]["mimic_damping_ratio"] == 1.0
    assert len(p["post_processing"]["self_collision_filtered_pairs"]) == 7  # 6.1.4
    assert p["converter"]["convert_mimic_joints_to_normal_joints"] is True  # 字段名与效果相反（6.1.2）


def test_wheeled_roller_key_is_last():
    # 转换器按字典顺序应用正则键，后键覆盖前键；被动滚子的键必须在通配之后（6.1.2）
    stiffness, damping = conversion.gains("wheeled")
    assert list(stiffness)[-1] == conversion.PASSIVE_ROLLER and stiffness[conversion.PASSIVE_ROLLER] == 0.0
    assert conversion.PASSIVE_ROLLER not in conversion.gains("fixed_base")[0]


@pytest.fixture
def generated(tmp_path, monkeypatch):
    """假的描述仓库与生成目录：只要有 urdf/ 子目录与几个输出文件即可。"""
    desc, gen = tmp_path / "desc", tmp_path / "gen"
    (desc / "urdf").mkdir(parents=True)
    out = gen / "galbot_fixed_base"
    (out / "configuration").mkdir(parents=True)
    (out / "galbot.usd").write_bytes(b"PXR-USDC fake")
    (out / "configuration" / "galbot_base.usd").write_bytes(b"base")
    (out / "config.yaml").write_text("# Generated by UrdfConverter on 2026-10-11\n")
    monkeypatch.setenv("GALBOT_DESCRIPTION_DIR", str(desc))
    monkeypatch.setenv("GALBOT_GENERATED_DIR", str(gen))
    manifest.write_manifest("fixed_base", False)
    return out


def test_manifest_roundtrip(generated):
    data = json.loads((generated / "MANIFEST.json").read_text())
    assert "config.yaml" not in data["files"]  # 带生成时间，不哈希
    assert manifest.verify_manifest("fixed_base", False) == []


def test_manifest_detects_param_change(generated, monkeypatch):
    monkeypatch.setattr(conversion, "MIMIC_NATURAL_FREQUENCY", 500.0)  # 改了代码参数，却没重新转换
    diffs = manifest.verify_manifest("fixed_base", False)
    assert any("mimic_natural_frequency" in d and "500.0" in d for d in diffs)


def test_manifest_detects_file_change(generated):
    with open(generated / "configuration" / "galbot_base.usd", "ab") as f:
        f.write(b" ")
    diffs = manifest.verify_manifest("fixed_base", False)
    assert len(diffs) == 1 and diffs[0].startswith("文件 configuration/galbot_base.usd")
